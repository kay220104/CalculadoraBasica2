public class Calculos {
    public int suma (int x, int y){
        return x+y;
        
    }
    
    public int resta (int x, int y){
        return x-y;
    }
    
    public int multi (int x, int y){
        return x*y;
    }
    
    public int divicion (int x, int y){
        return x/y;
    }
        
}
